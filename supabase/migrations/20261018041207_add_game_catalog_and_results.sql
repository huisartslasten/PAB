-- Central game catalog and result history.
-- Games own their runtime rules; game_results stores completed results
-- independently from the test-history tables.

create table public.games (
  id bigint generated by default as identity primary key,
  key text not null unique,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.game_results (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete restrict,
  lesson_id bigint not null references public.lessons(id) on delete restrict,
  student text not null,
  score integer not null default 0 check (score >= 0),
  played_at timestamptz not null default now()
);

create index game_results_game_lesson_student_idx
  on public.game_results (game_id, lesson_id, student);

create index game_results_student_lesson_idx
  on public.game_results (student, lesson_id);

alter table public.games enable row level security;
alter table public.game_results enable row level security;

create policy "Public can read active games"
  on public.games
  for select
  to anon, authenticated
  using (active = true);

create policy "Students can create game results"
  on public.game_results
  for insert
  to anon, authenticated
  with check (score >= 0);

create policy "Parents can view game results"
  on public.game_results
  for select
  to authenticated
  using (auth.uid() = 'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid);

