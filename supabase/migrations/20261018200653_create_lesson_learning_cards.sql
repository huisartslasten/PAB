create table if not exists public.lesson_learning_cards (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  title text not null default '',
  content text not null default '',
  image_id bigint references public.lesson_photos(id) on delete set null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists lesson_learning_cards_lesson_id_sort_order_idx
  on public.lesson_learning_cards (lesson_id, sort_order, id);

alter table public.lesson_learning_cards enable row level security;

create policy "learning cards readable to authenticated users"
  on public.lesson_learning_cards for select
  to authenticated
  using (true);

create policy "learning cards writable by authenticated users"
  on public.lesson_learning_cards for all
  to authenticated
  using (true)
  with check (true);
