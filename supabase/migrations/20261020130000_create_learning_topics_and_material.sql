create table if not exists public.learning_topics (
  id bigint generated by default as identity primary key,
  student text not null,
  subject text not null,
  subvak text not null default '',
  created_at timestamptz not null default now(),
  unique (student, subject, subvak)
);

create table if not exists public.learning_material_cards (
  id bigint generated by default as identity primary key,
  learning_topic_id bigint not null references public.learning_topics(id) on delete cascade,
  title text not null default '',
  document jsonb not null default '{"version":1,"elements":[]}'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists learning_material_cards_topic_order_idx
  on public.learning_material_cards (learning_topic_id, sort_order, id);

create table if not exists public.learning_topic_media (
  id bigint generated by default as identity primary key,
  learning_topic_id bigint not null references public.learning_topics(id) on delete cascade,
  storage_path text not null unique,
  original_name text not null default '',
  mime_type text not null default 'image/jpeg',
  size_bytes bigint not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists learning_topic_media_topic_idx
  on public.learning_topic_media (learning_topic_id, created_at, id);

alter table public.learning_topics enable row level security;
alter table public.learning_material_cards enable row level security;
alter table public.learning_topic_media enable row level security;

create policy "learning topics readable to authenticated users"
  on public.learning_topics for select to authenticated using (true);
create policy "learning topics writable by authenticated users"
  on public.learning_topics for all to authenticated using (true) with check (true);
create policy "learning material cards readable to authenticated users"
  on public.learning_material_cards for select to authenticated using (true);
create policy "learning material cards writable by authenticated users"
  on public.learning_material_cards for all to authenticated using (true) with check (true);
create policy "learning topic media readable to authenticated users"
  on public.learning_topic_media for select to authenticated using (true);
create policy "learning topic media writable by authenticated users"
  on public.learning_topic_media for all to authenticated using (true) with check (true);

insert into public.learning_topics (student, subject, subvak)
select distinct coalesce(student, ''), coalesce(subject, ''), coalesce(subvak, '')
from public.lessons
where coalesce(student, '') <> '' and coalesce(subject, '') <> ''
on conflict (student, subject, subvak) do nothing;

alter table public.lessons
  add column if not exists learning_topic_id bigint references public.learning_topics(id) on delete set null;

update public.lessons l
set learning_topic_id = t.id
from public.learning_topics t
where t.student = coalesce(l.student, '')
  and t.subject = coalesce(l.subject, '')
  and t.subvak = coalesce(l.subvak, '')
  and l.learning_topic_id is null;

create index if not exists lessons_learning_topic_id_idx on public.lessons (learning_topic_id);
