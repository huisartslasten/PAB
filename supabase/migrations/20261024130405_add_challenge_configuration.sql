-- Central persisted configuration for Challenges.
-- Runtime behavior consumes this configuration; Challenge pages do not own settings.

create table public.challenge_configurations (
  id bigint generated by default as identity primary key,
  challenge_key text not null unique,
  enabled boolean not null default true,
  unlock_policy jsonb not null default '{"type":"assessment-score","minimumScore":10}'::jsonb,
  ai_settings jsonb not null default '{}'::jsonb,
  game_settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index challenge_configurations_enabled_idx
  on public.challenge_configurations (enabled);

alter table public.challenge_configurations enable row level security;

create policy "Public can read challenge configurations"
  on public.challenge_configurations
  for select
  to anon, authenticated
  using (true);

create policy "Parents can manage challenge configurations"
  on public.challenge_configurations
  for all
  to authenticated
  using ((select auth.uid()) in (
    '5d0e1e5c-1dbe-4909-bd3a-81a1e7b26d09'::uuid,
    '418833d5-049a-4ec9-8072-2d48a85f04b1'::uuid,
    'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid
  ))
  with check ((select auth.uid()) in (
    '5d0e1e5c-1dbe-4909-bd3a-81a1e7b26d09'::uuid,
    '418833d5-049a-4ec9-8072-2d48a85f04b1'::uuid,
    'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid
  ));

