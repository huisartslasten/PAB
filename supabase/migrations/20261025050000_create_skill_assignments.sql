-- Per-student Skill availability.
-- The Skill registry owns the catalog; this table owns learner-specific assignments.

create table public.skill_assignments (
  id bigint generated by default as identity primary key,
  student text not null,
  skill_id text not null,
  enabled boolean not null default true,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student, skill_id)
);

create index skill_assignments_student_idx
  on public.skill_assignments (student, enabled, skill_id);

alter table public.skill_assignments enable row level security;

create policy "Public can read Skill assignments"
  on public.skill_assignments
  for select
  to anon, authenticated
  using (true);

create policy "Main administrator can insert Skill assignments"
  on public.skill_assignments
  for insert
  to authenticated
  with check (auth.uid() = 'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid);

create policy "Main administrator can update Skill assignments"
  on public.skill_assignments
  for update
  to authenticated
  using (auth.uid() = 'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid)
  with check (auth.uid() = 'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid);

create policy "Main administrator can delete Skill assignments"
  on public.skill_assignments
  for delete
  to authenticated
  using (auth.uid() = 'f0f92b9c-5eb7-4b78-aca0-1fea615b1999'::uuid);

insert into public.skill_assignments (student, skill_id)
select students.student, skills.skill_id
from (values ('Zyon'), ('Zenith'), ('Zephon')) as students(student)
cross join (values
  ('addition-easy'), ('addition-100'), ('addition-1000'), ('addition-10000'),
  ('subtraction-easy'), ('subtraction-100'), ('subtraction-1000'), ('subtraction-10000'),
  ('multiplication-easy'), ('multiplication-1-5'), ('multiplication-1-10'),
  ('math-mixed')
) as skills(skill_id)
on conflict (student, skill_id) do nothing;
